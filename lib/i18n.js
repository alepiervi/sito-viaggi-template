/**
 * Returns the translation for `keyPath` in the requested `lang`, using the
 * complete per-language dictionary. Falls back to Italian (DEFAULT_LANG) for any
 * key that is missing in the target language, then to the provided `fallback`,
 * then to the key itself.
 *
 * IMPORTANT: This resolves at React render time, so components that use t() render
 * natively in the selected language and can NEVER "revert" to Italian on re-render.
 * DomTranslator only handles strings that do NOT come through a translation key
 * (e.g. database-driven content fallbacks).
 */
export function tr(lang, keyPath, fallback = '') {
  const lookup = (code) => {
    const dict = dictionaries[code];
    if (!dict) return null;
    const parts = keyPath.split('.');
    let val = dict;
    for (const p of parts) {
      if (val && typeof val === 'object' && p in val) val = val[p];
      else return null;
    }
    return typeof val === 'string' ? val : null;
  };
  const result = lookup(lang);
  if (result != null) return result;
  const itResult = lookup(DEFAULT_LANG);
  if (itResult != null) return itResult;
  return fallback || keyPath;
}
